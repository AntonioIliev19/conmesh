package cli

import "unicode"

// runeWidth is the number of terminal columns a rune takes: 0 for combining
// marks and invisible format characters, 2 for East Asian wide and fullwidth
// characters and emoji, 1 otherwise. Menu redraws move the cursor up by the
// number of lines drawn, so a line that is wider than counted wraps and leaves
// a stale copy on screen.
func runeWidth(r rune) int {
	switch {
	case r == 0 || unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Me, r) || unicode.Is(unicode.Cf, r):
		return 0
	case r < 0x1100:
		return 1
	}
	for _, span := range wideRunes {
		if r < span[0] {
			return 1
		}
		if r <= span[1] {
			return 2
		}
	}
	return 1
}

