var ErrConflict = errors.New("HARNESS_CONFLICT: preserve existing or modified integration before retrying")
var ErrPackage = errors.New("HARNESS_PACKAGE: invalid portable entrypoint or metadata")

const header = "<!-- Generated by CONMESH; managed project integration. -->\n"
const begin = "# BEGIN CONMESH MANAGED MCP\n"
const end = "# END CONMESH MANAGED MCP\n"
const researchName = "conmesh-repository-research"
const researchSkillName = "conmesh-research"

// Portable harness names allow lowercase letters, digits and hyphens, max 64.
// A digest preserves identity when a package ID needs normalization or truncation.
func portableName(id string) string {
	base := strings.NewReplacer(".", "-", "_", "-").Replace(id)
	if base == id && len("conmesh-"+base) <= 64 {
		return "conmesh-" + base
	}
	const maxBase = 64 - len("conmesh-") - len("-") - 10
	if len(base) > maxBase {
		base = base[:maxBase]
	}
	h := sha256.Sum256([]byte(id))
	return fmt.Sprintf("conmesh-%s-%x", base, h[:5])
}

func entrypoint(p packages.Exported) (name, description, body string, err error) {
	data := p.Files["AGENT.md"]
	if p.Entry.Type == "skill" {
		data = p.Files["SKILL.md"]
	}
	if len(data) == 0 || !utf8.Valid(data) || bytes.IndexByte(data, 0) >= 0 || security.SensitiveContent(data) {
		err = ErrPackage
		return
	}
	body = string(data)
	name = portableName(p.Entry.ID)
	description = "CONMESH installed agent " + p.Entry.ID
	normalized := strings.ReplaceAll(body, "\r\n", "\n")
	if p.Entry.Type == "agent" && !strings.HasPrefix(normalized, "---\n") {
		// An agent without frontmatter is all instructions.
		if strings.TrimSpace(body) == "" {
			err = ErrPackage
		}
		return
	}
	if !strings.HasPrefix(normalized, "---\n") {
		err = ErrPackage
		return
	}
	front, rest, ok := strings.Cut(normalized[4:], "\n---\n")
	if !ok || len(front) > 8192 || strings.TrimSpace(rest) == "" {
		err = ErrPackage
		return
	}
	var meta map[string]any
	decoder := yaml.NewDecoder(strings.NewReader(front))
	if decoder.Decode(&meta) != nil {
		err = ErrPackage
		return
	}
	var extra any
	if decoder.Decode(&extra) != io.EOF {
		err = ErrPackage
		return
	}
	original, ok := meta["name"].(string)
	if !ok || original != p.Entry.ID {
		err = ErrPackage
		return
	}
	description, ok = meta["description"].(string)
	if !ok || !singleLine(description, 1024) {
		err = ErrPackage
		return
	}
	// Prevent packages from silently enabling hooks, tool grants or inline MCP.
	// The portable subset is deliberately instruction-only; supporting files
	// remain available. Optional keys can only describe or narrow behaviour.
	for key, value := range meta {
		if !optionalKeyOK(p.Entry.Type, key, value) {
			err = ErrPackage
			return
		}
	}
	if p.Entry.Type == "agent" {
		// Agent frontmatter is rebuilt per harness by renderPackages.
		body = rest
		return
	}
	meta["name"] = name
	encoded, e := yaml.Marshal(meta)
	if e != nil {
		err = ErrPackage
		return
	}
	body = "---\n" + string(encoded) + "---\n" + header + rest
	return
}

// agentModels are the Claude Code model aliases an agent may ask for.
var agentModels = map[string]bool{"inherit": true, "sonnet": true, "opus": true, "haiku": true}

// agentTools is a Claude Code tool allowlist such as "Read, Grep, Glob, Bash".
var agentTools = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*(, ?[A-Za-z][A-Za-z0-9_]*)*$`)

func singleLine(s string, max int) bool {
	return strings.TrimSpace(s) != "" && len(s) <= max && !strings.ContainsAny(s, "\x00\r\n")
}

// optionalKeyOK accepts the frontmatter keys ConMesh publishes. "tools" only
// narrows what an agent may use; it never grants a tool the user has not allowed.
func optionalKeyOK(kind, key string, value any) bool {
	switch key {
	case "name", "description":
		return true
	}
	if kind == "skill" {
		switch key {
		case "argument-hint":
			s, ok := value.(string)
			return ok && singleLine(s, 256)
		case "disable-model-invocation":
			_, ok := value.(bool)
			return ok
		}
		return false
	}
	switch key {
	case "model":
		s, ok := value.(string)
		return ok && agentModels[s]
	case "tools":
		s, ok := value.(string)
		return ok && len(s) <= 512 && agentTools.MatchString(s)
	}
	return false
}

// agentFront returns an agent's optional model and tools frontmatter.
func agentFront(data []byte) (model, tools string) {
	normalized := strings.ReplaceAll(string(data), "\r\n", "\n")
	front, _, ok := strings.Cut(strings.TrimPrefix(normalized, "---\n"), "\n---\n")
	if !ok || !strings.HasPrefix(normalized, "---\n") {
		return "", ""
	}
	var meta struct {
		Model string `yaml:"model"`
		Tools string `yaml:"tools"`
	}
	_ = yaml.Unmarshal([]byte(front), &meta)
	return meta.Model, meta.Tools
}

// indexTools are the CONMESH MCP tools as Claude Code names them.
var indexTools = []string{"mcp__conmesh__conmesh_search_codebase", "mcp__conmesh__conmesh_find_symbol", "mcp__conmesh__conmesh_find_reference_candidates", "mcp__conmesh__conmesh_index_status"}

// indexSection makes a published skill or agent use the project's ConMesh
// index. It is added only to projects with indexing enabled.
const indexSection = `

## ConMesh code index

This project has a ConMesh code index. When the task needs project code, query it before reading files broadly: ` + "`conmesh_find_symbol`" + ` for definitions, ` + "`conmesh_find_reference_candidates`" + ` for callers and uses (check them before changing a signature or deleting code), and ` + "`conmesh_search_codebase`" + ` for concepts and text. Then read only the files and lines the results point to. Reference results are lexical candidates, so confirm them in the source. If the CONMESH tools are unavailable, use normal file search.
`

// renderPackages publishes installed packages for one harness. With indexed
// set, every skill and agent is told to use the project's ConMesh index.
func renderPackages(h string, all []packages.Exported, indexed bool) (map[string][]byte, error) {
	files := map[string][]byte{}
	seen := map[string]bool{}
	for _, p := range all {
		name, description, body, err := entrypoint(p)
		if err != nil {
			return nil, err
		}
		if indexed {
			body = strings.TrimRight(body, "\n") + indexSection
		}
		identity := p.Entry.Type + ":" + name
		if seen[identity] {
			return nil, ErrConflict
		}
		seen[identity] = true
		if p.Entry.Type == "agent" {
			if h == "claude" {
				var front yaml.Node
				front.Kind = yaml.MappingNode
				add := func(k, v string) {
					front.Content = append(front.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, &yaml.Node{Kind: yaml.ScalarNode, Value: v})
				}
				add("name", name)
				add("description", description)
				model, tools := agentFront(p.Files["AGENT.md"])
				if model != "" {
					add("model", model)
				}
				if tools != "" {
					if indexed {
						// An agent limited to some tools still needs the index.
						tools += ", " + strings.Join(indexTools, ", ")
					}
					add("tools", tools)
				}
				encoded, err := yaml.Marshal(&front)
				if err != nil {
					return nil, ErrPackage
				}
				files[".claude/agents/"+name+".md"] = []byte("---\n" + string(encoded) + "---\n" + header + body)
			} else {
				data, err := toml.Marshal(map[string]string{"name": name, "description": description, "developer_instructions": strings.TrimSpace(header + body)})
				if err != nil {
					return nil, ErrPackage
				}
				files[".codex/agents/"+name+".toml"] = append([]byte("# Generated by CONMESH; managed project integration.\n"), data...)
			}
			continue
		}
		base := ".agents/skills/" + name + "/"
		if h == "claude" {
			base = ".claude/skills/" + name + "/"
		}
		for path, data := range p.Files {
			folded := strings.ToLower(path)
			if security.HardDenied(path, false) || folded == ".conmesh" || strings.HasPrefix(folded, ".conmesh/") || strings.HasPrefix(folded, ".claude-plugin/") || strings.HasPrefix(folded, ".codex-plugin/") || folded == "agents/openai.yaml" || security.SensitiveContent(data) {
				return nil, ErrPackage
			}
			if path == "SKILL.md" {
				data = []byte(body)
			}
			files[base+path] = data
		}
	}
	for _, data := range files {
		if len(data) > packages.MaxFileBytes {
			return nil, ErrPackage
		}
	}
	return files, nil
}

func addResearchSkill(base string, files map[string][]byte) error {
	dir := base + "/skills/" + researchSkillName
	entry, workflow := dir+"/SKILL.md", dir+"/workflow.md"
	if _, exists := files[entry]; exists {
		return ErrConflict
	}
	if _, exists := files[workflow]; exists {
		return ErrConflict
	}
	files[entry] = []byte(`---
name: conmesh-research
description: Run ConMesh research. Delegate project architecture and team-practice research to a local subagent that updates the CONMESH knowledge manifest.
---
` + header + `# Run ConMesh research

When the user asks to run ConMesh research, delegate from this conversation to
one local subagent that can use the project's CONMESH MCP tools, run CONMESH CLI
commands, and write knowledge proposals in the current project. Use the
` + researchName + ` custom subagent if your host offers it. Otherwise use a
local general-purpose subagent with those capabilities. Use foreground
delegation when needed for normal permission prompts.

Tell the worker to read ` + workflow + ` from the project root and execute that
workflow directly, without delegating it again. Wait for the worker's report
and return the validated proposal IDs and review digests or any blockers.
If your host cannot delegate locally, tell the user instead of claiming a
subagent ran. Keep this conversation and its current project.
`)
	files[workflow] = []byte(strings.ReplaceAll(knowledge.ResearchSkill, "\r\n", "\n"))
	return nil
}

func addResearchAgent(h string, files map[string][]byte) error {
	const description = "Research the local project and prepare evidence-backed knowledge proposals for review."
	workflow := ".agents/skills/" + researchSkillName + "/workflow.md"
	agentPath := ".codex/agents/" + researchName + ".toml"
	if h == "claude" {
		workflow = ".claude/skills/" + researchSkillName + "/workflow.md"
		agentPath = ".claude/agents/" + researchName + ".md"
	}
	if _, exists := files[agentPath]; exists {
		return ErrConflict
	}
	instructions := "Read `" + workflow + "` from the project root and execute the ConMesh research workflow directly. Report validated proposals for human review."
	if h == "claude" {
		meta, err := yaml.Marshal(map[string]string{"name": researchName, "description": description})
		if err != nil {
			return ErrPackage
		}
		files[agentPath] = []byte("---\n" + string(meta) + "---\n" + header + instructions + "\n")
		return nil
	}
	data, err := toml.Marshal(map[string]string{"name": researchName, "description": description, "developer_instructions": instructions})
	if err != nil {
		return ErrPackage
	}
	files[agentPath] = append([]byte("# Generated by CONMESH; managed project integration.\n"), data...)
	return nil
}

func mcpEntry(project, executable string) map[string]any {
	return map[string]any{"command": executable, "args": []string{"mcp", "serve", "--project", project}}
}

// jsonObject rejects duplicate keys at every depth instead of silently discarding
// a user's settings during a map round trip.
func jsonObject(data []byte) (map[string]json.RawMessage, error) {
	if len(data) == 0 {
		return map[string]json.RawMessage{}, nil
	}
	d := json.NewDecoder(bytes.NewReader(data))
	var walk func() error
	walk = func() error {
		token, err := d.Token()
		if err != nil {
			return err
		}
		delim, ok := token.(json.Delim)
		if !ok {
			return nil
		}
		if delim == '{' {
			seen := map[string]bool{}
			for d.More() {
				key, err := d.Token()
				if err != nil {
					return err
				}
				s, ok := key.(string)
				if !ok || seen[s] {
					return ErrConflict
				}
				seen[s] = true
				if err := walk(); err != nil {
					return err
				}
			}
		} else if delim == '[' {
			for d.More() {
				if err := walk(); err != nil {
					return err
				}
			}
		} else {
			return ErrConflict
		}
		_, err = d.Token()
		return err
	}
	if walk() != nil {
		return nil, ErrConflict
	}
	if _, err := d.Token(); err != io.EOF {
		return nil, ErrConflict
	}
	var value map[string]json.RawMessage
	if json.Unmarshal(data, &value) != nil || value == nil {
		return nil, ErrConflict
	}
	return value, nil
}
